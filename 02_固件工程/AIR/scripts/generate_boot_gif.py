"""Convert every boot GIF frame to baseline JPEG stored in firmware Flash.

The source GIF is preserved verbatim in assets. Frames retain their timing and
their complete composition, with proportional scaling to the target rectangle.
Run from any directory: python scripts/generate_boot_gif.py
Requires Pillow. Defaults: 160 x 214, JPEG quality 75, chroma subsampling 2.
"""

import argparse
from io import BytesIO
from pathlib import Path

from PIL import Image, ImageOps


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/boot-run-original.gif"
HEADER = ROOT / "include/boot_gif_data.h"
PREVIEW = ROOT / "assets/boot-run-converted-preview.gif"


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--header", type=Path, default=HEADER)
    parser.add_argument("--preview", type=Path, default=PREVIEW)
    parser.add_argument("--width", type=int, default=160)
    parser.add_argument("--height", type=int, default=214)
    parser.add_argument("--quality", type=int, default=75)
    args = parser.parse_args()
    if not (1 <= args.width <= 65535 and 1 <= args.height <= 65535):
        parser.error("width and height must fit in a positive uint16_t")
    if not 1 <= args.quality <= 100:
        parser.error("quality must be between 1 and 100")
    return args


def array_lines(values, per_line=12):
    return [
        "  " + ", ".join(str(value) for value in values[start:start + per_line]) + ","
        for start in range(0, len(values), per_line)
    ]


def main():
    args = parse_args()
    durations = []
    offsets = [0]
    payload = bytearray()
    preview_frames = []
    with Image.open(args.source) as original:
        if original.n_frames > 65535:
            raise ValueError("frame count does not fit in uint16_t")
        for index in range(original.n_frames):
            # Sequential seek applies the original GIF's disposal/compositing.
            original.seek(index)
            frame = original.convert("RGB")
            duration = int(original.info.get("duration", 100))
            if not 1 <= duration <= 65535:
                raise ValueError(f"frame {index}: duration must fit positive uint16_t")
            frame = ImageOps.pad(
                frame,
                (args.width, args.height),
                method=Image.Resampling.LANCZOS,
                color=(255, 255, 255),
            )
            encoded = BytesIO()
            frame.save(
                encoded,
                format="JPEG",
                quality=args.quality,
                subsampling=2,
                optimize=True,
                progressive=False,
            )
            jpeg = encoded.getvalue()
            with Image.open(BytesIO(jpeg)) as decoded:
                decoded.load()
                if decoded.size != (args.width, args.height):
                    raise ValueError(f"frame {index}: unexpected JPEG dimensions")
                if decoded.info.get("progressive") or decoded.info.get("progression"):
                    raise ValueError(f"frame {index}: JPEG must be baseline")
                preview_frames.append(decoded.copy())
            payload.extend(jpeg)
            offsets.append(len(payload))
            durations.append(duration)

    lines = [
        "// Generated by scripts/generate_boot_gif.py; do not edit manually.",
        "// All source frames; baseline JPEG, 4:2:0 chroma, original frame timing.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"static constexpr uint16_t BOOT_GIF_WIDTH = {args.width};",
        f"static constexpr uint16_t BOOT_GIF_HEIGHT = {args.height};",
        f"static constexpr uint16_t BOOT_GIF_FRAME_COUNT = {len(durations)};",
        f"static constexpr uint32_t BOOT_GIF_DURATION_MS = {sum(durations)};",
        "",
        "static const uint8_t BOOT_GIF_JPEG_DATA[] = {",
    ]
    for start in range(0, len(payload), 16):
        lines.append("  " + ", ".join(f"0x{value:02X}" for value in payload[start:start + 16]) + ",")
    lines += [
        "};",
        "",
        "// One start offset per frame, followed by the total data size.",
        "static constexpr uint32_t BOOT_GIF_FRAME_OFFSETS[BOOT_GIF_FRAME_COUNT + 1] = {",
    ]
    lines += array_lines(offsets[:-1])
    lines += [
        "  sizeof(BOOT_GIF_JPEG_DATA),",
        "};",
        "",
        "static constexpr uint16_t BOOT_GIF_FRAME_DURATIONS_MS[BOOT_GIF_FRAME_COUNT] = {",
    ]
    lines += array_lines(durations)
    lines += [
        "};",
        "",
        "static_assert(sizeof(BOOT_GIF_JPEG_DATA) <= UINT32_MAX, \"Boot GIF offsets overflow\");",
        "",
    ]
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text("\n".join(lines), encoding="ascii")
    args.preview.parent.mkdir(parents=True, exist_ok=True)
    preview_frames[0].save(
        args.preview,
        format="GIF",
        save_all=True,
        append_images=preview_frames[1:],
        duration=durations,
        loop=0,
        disposal=2,
        optimize=False,
    )
    with Image.open(args.preview) as preview:
        preview_durations = []
        for index in range(preview.n_frames):
            preview.seek(index)
            preview_durations.append(preview.info["duration"])
        if preview.n_frames != len(durations) or preview_durations != durations:
            raise ValueError("preview did not preserve every frame and duration")
    print(f"Frames: {len(durations)}, dimensions: {args.width} x {args.height}")
    print(f"Duration: {sum(durations)} ms; JPEG data: {len(payload)} bytes")
    print(f"Offset table: {len(offsets) * 4} bytes; duration table: {len(durations) * 2} bytes")
    print(f"Header: {args.header}")
    print(f"Preview: {args.preview}")


if __name__ == "__main__":
    main()
