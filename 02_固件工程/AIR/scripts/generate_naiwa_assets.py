"""Export the approved Naiwa PNG and a small Chinese font subset for the TFT.

This performs device-format conversion only; the approved character is not
redrawn. Pillow is the only build-time dependency, and is not needed to compile
or run the firmware. Run from any directory with Python 3.9 or newer:

    python scripts/generate_naiwa_assets.py

On another machine, supply a local Microsoft YaHei font with --font PATH.
--preview PATH optionally writes a readable contact sheet for asset inspection.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = ROOT / "assets/naiwa-original.png"
DEFAULT_HEADER = ROOT / "include/naiwa_ui_assets.h"
DEFAULT_FONT = Path("C:/Windows/Fonts/msyh.ttc")
MASCOT_SIZE = (76, 80)
SIDEBAR_RGB = (255, 241, 200)
GLYPH_SIZE = 12
GLYPH_ROW_BYTES = 2
UI_TEXT = (
    "奶娃空气站我在认真采集数据等我醒醒预热秒我没收到传感器数据"
    "正在采集刚刚更新蓝牙上报等待传感器读数暂不可用温度湿度甲醛"
    "故障报警暂停关闭更新中正常检查稍后重试前"
)


def rgb565(rgb: tuple[int, int, int]) -> int:
    red, green, blue = rgb
    return ((red & 0xF8) << 8) | ((green & 0xFC) << 3) | (blue >> 3)


def mascot_bitmap(source: Path) -> Image.Image:
    with Image.open(source) as original:
        original = original.convert("RGBA")
        # Preserve the supplied canvas and pose to match the approved mockup.
        original.thumbnail(MASCOT_SIZE, Image.Resampling.LANCZOS)
        canvas = Image.new("RGBA", MASCOT_SIZE, SIDEBAR_RGB + (255,))
        offset = tuple((a - b) // 2 for a, b in zip(MASCOT_SIZE, original.size))
        canvas.alpha_composite(original, offset)
        return canvas.convert("RGB")


def make_glyph(character: str, font: ImageFont.FreeTypeFont) -> tuple[bytes, Image.Image]:
    tile = Image.new("L", (GLYPH_SIZE, GLYPH_SIZE), 0)
    bounds = font.getbbox(character)
    ink_width, ink_height = bounds[2] - bounds[0], bounds[3] - bounds[1]
    if ink_width > GLYPH_SIZE or ink_height > GLYPH_SIZE:
        raise ValueError(f"Font glyph does not fit 12x12: {character!r}: {bounds}")
    origin = (
        (GLYPH_SIZE - ink_width) // 2 - bounds[0],
        (GLYPH_SIZE - ink_height) // 2 - bounds[1],
    )
    ImageDraw.Draw(tile).text(origin, character, font=font, fill=255)
    # Keep lighter one-pixel strokes in the small YaHei raster.
    mono = tile.point(lambda value: 255 if value >= 96 else 0)
    packed = bytearray()
    for y in range(GLYPH_SIZE):
        bits = sum((1 << (15 - x)) for x in range(GLYPH_SIZE) if mono.getpixel((x, y)))
        packed.extend((bits >> 8, bits & 0xFF))
    if not any(packed):
        raise ValueError(f"Blank glyph: {character!r}")
    assert len(packed) == GLYPH_SIZE * GLYPH_ROW_BYTES
    return bytes(packed), mono


def write_header(header: Path, mascot: Image.Image, glyphs: list[tuple[str, bytes]]) -> None:
    lines = [
        "// Generated by scripts/generate_naiwa_assets.py; do not edit manually.",
        "// Approved Naiwa artwork, composited onto sidebar #FFF1C8.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "#ifdef PROGMEM",
        "#define NAIWA_ASSET_FLASH PROGMEM",
        "#else",
        "#define NAIWA_ASSET_FLASH",
        "#endif",
        "",
        "namespace NaiwaAssets {",
        f"constexpr int16_t MASCOT_WIDTH = {MASCOT_SIZE[0]};",
        f"constexpr int16_t MASCOT_HEIGHT = {MASCOT_SIZE[1]};",
        f"constexpr uint16_t MASCOT_BACKGROUND = 0x{rgb565(SIDEBAR_RGB):04X};",
        "// Row-major RGB565 values, suitable for Adafruit_GFX::drawRGBBitmap.",
        "static const uint16_t mascot[] NAIWA_ASSET_FLASH = {",
    ]
    rgb_bytes = mascot.tobytes()
    pixels = [rgb565(tuple(rgb_bytes[start:start + 3]))
              for start in range(0, len(rgb_bytes), 3)]
    for start in range(0, len(pixels), 12):
        lines.append("  " + ", ".join(f"0x{value:04X}" for value in pixels[start:start + 12]) + ",")
    lines.extend([
        "};",
        "",
        f"constexpr uint8_t GLYPH_WIDTH = {GLYPH_SIZE};",
        f"constexpr uint8_t GLYPH_HEIGHT = {GLYPH_SIZE};",
        f"constexpr uint8_t GLYPH_ROW_BYTES = {GLYPH_ROW_BYTES};",
        "// 12x12 monochrome glyphs from Microsoft YaHei, font size 12 px.",
        "// Each row is two bytes, big endian / MSB first: x=0 uses bit 15.",
        "// Only the top 12 bits of each row are used; bottom four bits are zero.",
        "// Entries are sorted by Unicode code point for optional binary search.",
        "struct Glyph {",
        "  uint16_t unicode;",
        "  uint8_t bitmap[24];",
        "};",
        "static const Glyph glyphs[] NAIWA_ASSET_FLASH = {",
    ])
    for character, packed in glyphs:
        row = ", ".join(f"0x{value:02X}" for value in packed)
        lines.append(f"  {{0x{ord(character):04X}, {{{row}}}}}, // {character}")
    lines.extend([
        "};",
        f"constexpr uint16_t GLYPH_COUNT = {len(glyphs)};",
        "static_assert(sizeof(mascot) == MASCOT_WIDTH * MASCOT_HEIGHT * 2,",
        '              "Naiwa RGB565 bitmap size mismatch");',
        "static_assert(sizeof(Glyph) == 26, \"Naiwa glyph storage size mismatch\");",
        "} // namespace NaiwaAssets",
        "",
        "#undef NAIWA_ASSET_FLASH",
        "",
    ])
    header.parent.mkdir(parents=True, exist_ok=True)
    header.write_text("\n".join(lines), encoding="utf-8")


def save_preview(path: Path, mascot: Image.Image, glyph_tiles: list[tuple[str, Image.Image]],
                 font: ImageFont.FreeTypeFont) -> None:
    columns, cell_width, cell_height = 12, 44, 52
    rows = (len(glyph_tiles) + columns - 1) // columns
    canvas = Image.new("RGB", (columns * cell_width, 180 + rows * cell_height), "#FFF9E9")
    canvas.paste(mascot.resize((152, 160), Image.Resampling.NEAREST), (6, 6))
    draw = ImageDraw.Draw(canvas)
    draw.text((176, 16), "76x80 RGB565 mascot (2x)", fill="#483B27")
    draw.text((176, 38), "12x12 1-bit subset (2x below)", fill="#483B27")
    for index, (character, tile) in enumerate(glyph_tiles):
        x = index % columns * cell_width + 8
        y = 180 + index // columns * cell_height
        ink = Image.new("RGB", tile.size, "#483B27")
        background = Image.new("RGB", tile.size, "#FFF9E9")
        raster = Image.composite(ink, background, tile)
        canvas.paste(raster.resize((24, 24), Image.Resampling.NEAREST), (x, y))
        draw.text((x, y + 28), character, font=font, fill="#796D53")
    path.parent.mkdir(parents=True, exist_ok=True)
    canvas.save(path)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--header", type=Path, default=DEFAULT_HEADER)
    parser.add_argument("--font", type=Path, default=DEFAULT_FONT)
    parser.add_argument("--preview", type=Path)
    args = parser.parse_args()
    if not args.source.is_file():
        parser.error(f"Approved PNG not found: {args.source}")
    if not args.font.is_file():
        parser.error(f"Chinese font not found; supply --font: {args.font}")
    font = ImageFont.truetype(str(args.font), GLYPH_SIZE)
    mascot = mascot_bitmap(args.source)
    glyphs, glyph_tiles = [], []
    for character in sorted(set(UI_TEXT)):
        packed, tile = make_glyph(character, font)
        glyphs.append((character, packed))
        glyph_tiles.append((character, tile))
    write_header(args.header, mascot, glyphs)
    if args.preview:
        save_preview(args.preview, mascot, glyph_tiles, font)
    print(f"Mascot: {MASCOT_SIZE[0]}x{MASCOT_SIZE[1]}, {MASCOT_SIZE[0] * MASCOT_SIZE[1] * 2} bytes")
    print(f"Font: {len(glyphs)} glyphs, 12x12, {len(glyphs) * 26} bytes including Unicode indices")
    print(f"Header: {args.header}")


if __name__ == "__main__":
    main()
